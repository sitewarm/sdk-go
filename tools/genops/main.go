// genops writes ops_gen.go: the operationId -> method/path/idempotency table used by the runtime client.
// usage: genops SPEC OUT
package main

import (
	"fmt"
	"os"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"
)

type param struct {
	Ref string `yaml:"$ref"`
}

type operation struct {
	OperationID string  `yaml:"operationId"`
	Parameters  []param `yaml:"parameters"`
}

// prep writes a copy of the spec without webhook callbacks (server-to-customer, not part of the SDK) so the
// type generator does not emit event types that have no schema in components.
func prep(in, out string) {
	raw, err := os.ReadFile(in)
	if err != nil {
		panic(err)
	}
	var spec map[string]any
	if err := yaml.Unmarshal(raw, &spec); err != nil {
		panic(err)
	}
	delete(spec, "webhooks")
	if comps, ok := spec["components"].(map[string]any); ok {
		delete(comps, "callbacks")
	}
	paths, _ := spec["paths"].(map[string]any)
	for _, item := range paths {
		if m, ok := item.(map[string]any); ok {
			for _, op := range m {
				if o, ok := op.(map[string]any); ok {
					delete(o, "callbacks")
				}
			}
		}
	}
	b, err := yaml.Marshal(spec)
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile(out, b, 0o644); err != nil {
		panic(err)
	}
}

func main() {
	if os.Args[1] == "prep" {
		prep(os.Args[2], os.Args[3])
		return
	}
	raw, err := os.ReadFile(os.Args[1])
	if err != nil {
		panic(err)
	}
	var spec struct {
		Paths map[string]map[string]yaml.Node `yaml:"paths"`
	}
	if err := yaml.Unmarshal(raw, &spec); err != nil {
		panic(err)
	}
	type row struct{ id, method, path, idem string }
	var rows []row
	for path, item := range spec.Paths {
		var shared []param
		if n, ok := item["parameters"]; ok {
			_ = n.Decode(&shared)
		}
		for _, m := range []string{"get", "put", "post", "patch", "delete"} {
			n, ok := item[m]
			if !ok {
				continue
			}
			var op operation
			if err := n.Decode(&op); err != nil {
				panic(err)
			}
			idem := "IdempotencyNone"
			for _, p := range append(append([]param{}, shared...), op.Parameters...) {
				switch {
				case strings.HasSuffix(p.Ref, "/IdempotencyKeyRequired"):
					idem = "IdempotencyRequired"
				case strings.HasSuffix(p.Ref, "/IdempotencyKey"):
					idem = "IdempotencyOptional"
				}
			}
			rows = append(rows, row{op.OperationID, strings.ToUpper(m), path, idem})
		}
	}
	sort.Slice(rows, func(i, j int) bool { return rows[i].id < rows[j].id })
	var b strings.Builder
	b.WriteString("// Code generated by tools/genops from openapi/openapi.yaml. DO NOT EDIT.\n\npackage sitewarm\n\n")
	b.WriteString("var operations = map[string]operation{\n")
	for _, r := range rows {
		fmt.Fprintf(&b, "\t%q: {method: %q, path: %q, idempotency: %s},\n", r.id, r.method, r.path, r.idem)
	}
	b.WriteString("}\n")
	if err := os.WriteFile(os.Args[2], []byte(b.String()), 0o644); err != nil {
		panic(err)
	}
	fmt.Printf("generated %d operations\n", len(rows))
}
